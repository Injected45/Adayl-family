-- ============================================================================
--  WHY_NO_AID4.sql — استعلام واحد، لأن المحرّر يعرض آخر جدول فقط.
--
--  READ-ONLY.
--
--  ⚠ هذا سبب دوران الفحوص الثلاثة السابقة: كل ملف فيها استعلامان أو ثلاثة،
--    ومحرّر Supabase يعرض نتيجة الأخير وحده — فالجدول الذي كنت أنتظره لم يظهر
--    قط. هنا استعلام واحد، فما تراه هو ما سألتُ عنه.
--
--  ── ما استُبعد حتى الآن ─────────────────────────────────────────────────────
--  الجدول، والدالة، والسياسة، والامتياز، و my_adeel_id — كلها سليمة. وأيمن
--  (A-06) مربوط بجهاز وحسابه معتمد ورمزه مُستَرد، فليست مسألة جهاز.
--
--  ── ما يسأل عنه هذا ─────────────────────────────────────────────────────────
--  ماذا تُرجع api_adeel_aid بالضبط لكل من صُرف له — بصلاحيات المالك، فتتجاوز
--  RLS. إن ظهرت الأسطر هنا وغابت على الهاتف فالسبب في السياسة أو في نسخة
--  التطبيق؛ وإن غابت هنا أيضاً فالعطل في الدالة نفسها ولا علاقة له بالمشترك.
-- ============================================================================

SELECT
  a.adeel_code                                        AS "الرمز",
  a.full_name                                         AS "الاسم",

  -- كم سنداً في الجدول فعلاً، بلا أي دالة بينهما.
  (SELECT count(*) FROM public.disbursements d
    WHERE d.payee_adeel_id = a.id)                    AS "سندات في الجدول",

  -- وماذا تقول الدالة: الإجمالي والعدد يعملان (رأيناهما)، والسؤال هو الأسطر.
  (public.api_adeel_aid(a.id) ->> 'total')            AS "إجمالي الدالة",
  (public.api_adeel_aid(a.id) ->> 'count')            AS "عدد الدالة",

  -- ‹‹ الجواب ›› — طول مصفوفة vouchers، وهي ما يرسمه التطبيق سطراً سطراً.
  jsonb_array_length(
    coalesce(public.api_adeel_aid(a.id) -> 'vouchers', '[]'::jsonb))
                                                      AS "أسطر vouchers",

  -- وأسماء المفاتيح التي تعود فعلاً، فإن اختلف اسم عن الذي يقرأه التطبيق
  -- ظهرت الشاشة فارغة بلا خطأ — وهو بالضبط ما أوقعني في الفحص الثاني.
  (SELECT string_agg(k, ' | ' ORDER BY k)
     FROM jsonb_object_keys(public.api_adeel_aid(a.id)) k)
                                                      AS "مفاتيح الجواب",

  -- وأوّل سطر كما يصل التطبيق، إن وُجد. فارغ هنا مع عدد أكبر من صفر يعني أن
  -- الوصلة بـ v_disbursements هي التي تسقط الأسطر.
  coalesce(
    (public.api_adeel_aid(a.id) -> 'vouchers' -> 0)::text, '—')
                                                      AS "أوّل سطر"
FROM public.adeels a
WHERE EXISTS (SELECT 1 FROM public.disbursements d WHERE d.payee_adeel_id = a.id)
ORDER BY a.id;
