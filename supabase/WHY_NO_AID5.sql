-- ============================================================================
--  WHY_NO_AID5.sql — آخر السندات، ولمن سُجِّل كلٌّ منها.
--
--  READ-ONLY. استعلام واحد، فالمحرّر يعرض آخر جدول فقط.
--
--  ── ما نعرفه ────────────────────────────────────────────────────────────────
--  أيمن يرى بوابته كاملة، ويرى شاشة الصرف وفيها أربع معاملات. فالسياسة تعمل،
--  والجهاز مربوط، والدالة تُرجع أسطرها. الناقص هو الأحدث وحده — وهذا شكل الجواب
--  المخزَّن في الهاتف بالضبط.
--
--  ── ما يسأل عنه هذا ─────────────────────────────────────────────────────────
--  أن السند الجديد سُجِّل فعلاً باسم أيمن. «نقص الصندوق» يثبت أن الصرف حدث، ولا
--  يثبت لمن — سندٌ سُجِّل «جماعياً» أو باسم عديل آخر ينقص الصندوق تماماً كما
--  ينقصه سنده هو، ولا يظهر عنده أبداً وهذا صحيح لا عطل.
--
--  اقرأ الصفّ الأوّل: إن كان اسمه أيمن فالقاعدة سليمة والباقي في نسخة التطبيق
--  على هاتفه. وإن كان اسماً آخر أو «جماعي» فقد وجدنا السبب، وليس في البرنامج.
-- ============================================================================

SELECT
  d.voucher_no                                   AS "رقم السند",
  to_char(d.spent_at AT TIME ZONE 'UTC',
          'YYYY-MM-DD HH24:MI')                  AS "وقت التسجيل",
  d.amount                                       AS "المبلغ",
  d.kind::text                                   AS "النوع",
  d.category::text                               AS "الوجه",
  d.status::text                                 AS "الحالة",
  coalesce(a.adeel_code, '—')                    AS "رمز المستفيد",
  coalesce(a.full_name, '‹‹ جماعي — لا يظهر عند أحد ››') AS "المستفيد",
  -- وهل تصل الدالة إليه: العدد الذي ستعيده لهذا المستفيد الآن.
  CASE WHEN d.payee_adeel_id IS NULL THEN '—'
       ELSE (public.api_adeel_aid(d.payee_adeel_id) ->> 'count')
  END                                            AS "ما تعيده الدالة له الآن"
FROM public.disbursements d
LEFT JOIN public.adeels a ON a.id = d.payee_adeel_id
ORDER BY d.id DESC
LIMIT 6;
